import type { ClientReferralsQuery } from './__generated__/Referrals.generated';
import { INTAKE_FIELDS, isIntakeControlValue } from '../../../draft/intakeFields';
import {
  formatReferralTimestamp,
  localReferralDay,
  referralArrival,
} from './referralPresentation';
import { referralProfileRows, type ProfileCardData } from './referralProfile';
import {
  canEditReferralNotes,
  decodeReferralNotes,
} from './referralIntakeSidecar';

export type ExportReferral =
  ClientReferralsQuery['referrals']['results'][number];
export type ReferralTextCopy = { title: string; text: string };
export type ReferralDocumentBlock =
  | { kind: 'title' | 'heading' | 'note'; text: string }
  | { kind: 'field'; label: string; value: string; tone?: 'warning' }
  | { kind: 'space' };
export type ReferralDocumentCopy = ReferralTextCopy & {
  blocks: readonly ReferralDocumentBlock[];
};

type ReferralExportInput = {
  referral: ExportReferral;
  clientName: string;
  profile?: ProfileCardData | null;
  generatedAt: string;
  includePrivate?: boolean;
};

function documentField(label: string, value: string): ReferralDocumentBlock {
  return { kind: 'field', label, value };
}
function note(text: string): ReferralDocumentBlock {
  return { kind: 'note', text };
}

export function referralDocumentBlockText(
  block: ReferralDocumentBlock,
): string {
  if (block.kind === 'space') return '';
  return block.kind === 'field' ? `${block.label}: ${block.value}` : block.text;
}

/** A readable copy of this saved referral, never the client's active draft. */
export function buildReferralDocumentCopy({
  referral,
  clientName,
  profile,
  generatedAt,
  includePrivate = false,
}: ReferralExportInput): ReferralDocumentCopy {
  if (!canEditReferralNotes(referral.notes)) {
    throw new Error(
      'This referral uses an unreadable or newer intake format. A reliable summary cannot be generated by this app version.',
    );
  }
  const { humanNotes, intake } = decodeReferralNotes(referral.notes);
  const arrival = referralArrival(
    intake.requestedArrivalDate,
    localReferralDay(new Date(generatedAt).getTime()),
  );
  const arrivalValue = arrival
    ? `${arrival.value}${arrival.isPast ? ' (Past)' : ''}`
    : intake.requestedArrivalDate != null && intake.requestedArrivalDate !== ''
      ? 'Unrecognized saved answer; review the original referral'
      : 'Not recorded';
  const profileRows = referralProfileRows(profile, clientName);
  const referrer =
    [referral.createdBy?.firstName, referral.createdBy?.lastName]
      .filter(Boolean)
      .join(' ')
      .trim() || 'Not recorded';
  const status =
    referral.status === 'ACCEPTED'
      ? 'Accepted'
      : referral.status === 'DECLINED'
        ? 'Declined'
        : referral.status === 'PENDING'
          ? 'Pending — shelter decision not recorded'
          : 'Not recorded';
  const blocks: ReferralDocumentBlock[] = [
    { kind: 'title', text: 'Better Angels — referral summary' },
    documentField('Referral ID', referral.id),
    documentField(
      'Client (current profile name)',
      profileRows[0].value ?? 'Not recorded',
    ),
    documentField('Shelter', referral.shelter?.name || 'Not recorded'),
    documentField(
      'Shelter address',
      referral.shelter?.location?.place || 'Not recorded',
    ),
    {
      kind: 'field',
      label: 'Requested arrival date',
      value: arrivalValue,
      ...(arrival?.isPast ? { tone: 'warning' as const } : {}),
    },
    documentField('Referred', formatReferralTimestamp(referral.createdAt)),
    documentField('Referrer', referrer),
    documentField('Recorded outcome', status),
    documentField('Copy generated', formatReferralTimestamp(generatedAt)),
    { kind: 'space' },
    note(
      'This copy does not confirm shelter receipt, a bed or a reservation. Contact the shelter to confirm availability and arrangements.',
    ),
    { kind: 'space' },
    note(
      includePrivate
        ? 'Sensitive information: Included when recorded.'
        : 'Sensitive information: Excluded.',
    ),
    note(
      'Client identity and basic profile facts are included in both copies.',
    ),
    note(
      '[Sensitive] identifies fields controlled by the sharing privacy option. It does not assess the client or shelter eligibility.',
    ),
    { kind: 'space' },
    {
      kind: 'heading',
      text: 'Client profile (current profile values, not a snapshot at referral creation)',
    },
  ];
  for (const row of profileRows) {
    const value =
      row.sensitive && !includePrivate
        ? 'Excluded (sensitive)'
        : (row.value ?? 'Not recorded');
    const label = row.label + (row.sensitive ? ' [Sensitive]' : '');
    blocks.push(documentField(label, value));
  }
  blocks.push(
    { kind: 'space' },
    { kind: 'heading', text: 'Saved referral intake' },
    note(
      'Not recorded means unknown, not No. Unsaved draft changes are not included.',
    ),
  );
  let omitted = false;
  for (const field of INTAKE_FIELDS) {
    // Arrival is prominent above, rather than duplicated in the intake tail.
    if (field.key === 'requestedArrivalDate') continue;
    // Staff notes may contain private details even though their form metadata
    // describes a direct text mapping rather than a sensitive sidecar bucket.
    const sensitive = field.sensitive || field.backend.mode === 'direct';
    const label = field.label + (sensitive ? ' [Sensitive]' : '');
    if (sensitive && !includePrivate) {
      blocks.push(documentField(label, 'Excluded (sensitive)'));
      continue;
    }
    const value =
      field.backend.mode === 'direct' ? humanNotes : intake[field.key];
    if (
      value == null ||
      (typeof value === 'string' && !value.trim()) ||
      (Array.isArray(value) && !value.length)
    ) {
      blocks.push(documentField(label, 'Not recorded'));
      continue;
    }
    if (!isIntakeControlValue(field, value)) {
      omitted = true;
      blocks.push(
        documentField(
          label,
          'Unrecognized saved answer; review the original referral',
        ),
      );
      continue;
    }
    const display =
      field.control === 'multiselect' && Array.isArray(value)
        ? value
            .map(
              (item) =>
                field.options.find((option) => option.value === item)?.label,
            )
            .join(', ')
        : typeof value === 'boolean'
          ? value
            ? 'Yes'
            : 'No'
          : String(value);
    blocks.push(documentField(label, display));
  }
  blocks.push(
    { kind: 'space' },
    note(
      'Reference-only Smartsheet fields are not collected by this form and have no answers in this copy.',
    ),
    note(
      'The consent answer is a recorded yes/no, not a signed consent document.',
    ),
  );
  if (!includePrivate)
    blocks.push(
      { kind: 'space' },
      note('Sensitive intake and staff notes excluded from this copy.'),
    );
  if (
    Object.keys(intake).some(
      (key) => !INTAKE_FIELDS.some((field) => field.key === key),
    )
  )
    omitted = true;
  if (omitted)
    blocks.push(
      { kind: 'space' },
      note(
        'Some saved answers use older or unrecognized fields/values and are omitted. Review the original referral; this is not a complete archival copy.',
      ),
    );
  const text = blocks.map(referralDocumentBlockText).join('\n');
  return { title: 'Better Angels referral summary', text, blocks };
}

export function buildReferralTextCopy(
  input: ReferralExportInput,
): ReferralTextCopy {
  const { title, text } = buildReferralDocumentCopy(input);
  return { title, text };
}
