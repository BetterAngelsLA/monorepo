import type { ClientReferralsQuery } from './__generated__/Referrals.generated';
import { INTAKE_FIELDS, isIntakeControlValue } from './intakeFields';
import {
  canEditReferralNotes,
  decodeReferralNotes,
} from './referralIntakeSidecar';

export type ExportReferral =
  ClientReferralsQuery['referrals']['results'][number];
export type ReferralTextCopy = { title: string; text: string };

function timestamp(value: string | undefined): string {
  const date = value ? new Date(value) : null;
  if (!date || Number.isNaN(date.getTime())) return 'Not recorded';
  return date.toLocaleString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    timeZone: 'UTC',
    timeZoneName: 'short',
  });
}

/** A readable copy of this saved referral, never the client's active draft. */
export function buildReferralTextCopy({
  referral,
  clientName,
  generatedAt,
  includePrivate = false,
}: {
  referral: ExportReferral;
  clientName: string;
  generatedAt: string;
  includePrivate?: boolean;
}): ReferralTextCopy {
  if (!canEditReferralNotes(referral.notes)) {
    throw new Error(
      'This referral uses an unreadable or newer intake format. A reliable summary cannot be generated by this app version.',
    );
  }
  const { humanNotes, intake } = decodeReferralNotes(referral.notes);
  const referrer =
    [referral.createdBy?.firstName, referral.createdBy?.lastName]
      .filter(Boolean)
      .join(' ')
      .trim() || 'Not recorded';
  const status =
    referral.status === 'ACCEPTED'
      ? 'Accepted'
      : referral.status === 'DECLINED'
        ? 'Declined'
        : referral.status === 'PENDING'
          ? 'Pending — shelter decision not recorded'
          : 'Not recorded';
  const lines = [
    'Better Angels — referral summary',
    `Referral ID: ${referral.id}`,
    `Client (current profile name): ${clientName.trim() || 'Not recorded'}`,
    `Shelter: ${referral.shelter?.name || 'Not recorded'}`,
    `Shelter address: ${referral.shelter?.location?.place || 'Not recorded'}`,
    `Created: ${timestamp(referral.createdAt)}`,
    `Referrer: ${referrer}`,
    `Recorded outcome: ${status}`,
    `Copy generated: ${timestamp(generatedAt)}`,
    '',
    'This copy does not confirm shelter receipt, a bed or a reservation. Contact the shelter to confirm availability and arrangements.',
    '',
    'Referral information',
  ];
  let omitted = false;
  for (const field of INTAKE_FIELDS) {
    if (field.backend.mode === 'direct') continue;
    const value = intake[field.key];
    if (
      value == null ||
      value === '' ||
      (Array.isArray(value) && !value.length)
    )
      continue;
    if (field.sensitive && !includePrivate) continue;
    if (!isIntakeControlValue(field, value)) {
      omitted = true;
      continue;
    }
    const display =
      field.control === 'multiselect' && Array.isArray(value)
        ? value
            .map(
              (item) =>
                field.options.find((option) => option.value === item)?.label,
            )
            .join(', ')
        : typeof value === 'boolean'
          ? value
            ? 'Yes'
            : 'No'
          : String(value);
    lines.push(`${field.label}: ${display}`);
  }
  if (includePrivate && humanNotes)
    lines.push('', 'Staff observations / notes', humanNotes);
  if (!includePrivate)
    lines.push('', 'Sensitive intake and staff notes excluded from this copy.');
  if (
    Object.keys(intake).some(
      (key) => !INTAKE_FIELDS.some((field) => field.key === key),
    )
  )
    omitted = true;
  if (omitted)
    lines.push(
      '',
      'Some saved answers use older or unrecognized fields/values and are omitted. Review the original referral; this is not a complete archival copy.',
    );
  return { title: 'Better Angels referral summary', text: lines.join('\n') };
}
